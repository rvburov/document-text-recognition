using Avalonia.Controls;

namespace DocumentTextRecognition.Dialogs;

/// <summary>«Как сделать шаблон»: короткая инструкция.</summary>
public static class HowToDialog
{
    public static Task Show(Window owner) => Ask.Info(owner, "Как сделать шаблон",
        "1. Возьмите чистый скан документа и сохраните его в папку шаблонов, например «Спецификация.pdf».\n\n" +
        "2. Обведите в штампе поле обозначения синей рамкой, поле наименования зеленой, поле типа документа желтой. " +
        "Если все поля в одной клетке, обведите их одной красной рамкой.\n\n" +
        "3. Нажмите «Обновить»: шаблон появится в списке с пометкой «Распознан».",
        secondText: "Если тип документа на скане не написан, в имя файла ставится «Спецификация».");
}
