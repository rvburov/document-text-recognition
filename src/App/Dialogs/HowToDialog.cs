using Avalonia.Controls;

namespace DocumentTextRecognition.Dialogs;

/// <summary>«Как сделать шаблон»: короткая инструкция.</summary>
public static class HowToDialog
{
    public static Task Show(Window owner) => Ask.Info(owner, "Как сделать шаблон",
        "1. Положите PDF-образец в папку шаблонов. Выберите папку и файл в разделе «Шаблоны», нажмите «Разметить области…».\n\n" +
        "2. Выберите страницу и увеличьте штамп. Выберите цвет и выделите мышью текст: синий — обозначение, зеленый — наименование, желтый — тип документа. " +
        "Для всех полей вместе используйте одну красную область.\n\n" +
        "3. Если тип документа на скане не написан, вместо желтой области отметьте «Тип документа отсутствует: Спецификация».\n\n" +
        "4. Проверьте координаты под страницей. Область можно передвинуть, изменить за угловые маркеры или удалить. Нажмите «Сохранить шаблон».\n\n" +
        "5. «Сохранить и проверить…» позволяет выбрать скан и увидеть фрагменты полей, ответы двух способов распознавания и предлагаемое имя.",
        secondText: "Разметка сохраняется рядом с PDF в файле с окончанием .template.json. При переносе шаблона скопируйте оба файла.");
}
