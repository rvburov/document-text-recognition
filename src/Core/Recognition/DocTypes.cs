namespace DocumentTextRecognition.Core.Recognition;

/// <summary>
/// Типы конструкторских документов (ГОСТ 2.102, схемы по ГОСТ 2.701) и правила для поля
/// «тип документа».
///
/// <para>Желтая рамка: тип берется как прочитан; если он совпадает с типом из справочника
/// (без учета регистра, «ё» и букв-двойников), пишется так, как в справочнике.</para>
/// <para>Красная рамка: тип отделяется от наименования только по справочнику: последняя
/// строка, если она начинается словом типа, или известный тип в конце строки.</para>
/// <para>Тип на скане не написан (поле пустое у обоих способов): ставится
/// <see cref="WhenMissing"/> (решение владельца программы).</para>
/// </summary>
internal static class DocTypes
{
    /// <summary>Тип, если на скане он не написан.</summary>
    public const string WhenMissing = "Спецификация";

    public const int MaxLength = 100;

    /// <summary>Справочник. Длинные варианты раньше коротких: «Схема электрическая
    /// принципиальная» находится раньше «Схема электрическая».</summary>
    public static readonly IReadOnlyList<string> Known = new[]
    {
        "Чертеж детали", "Сборочный чертеж", "Чертеж общего вида", "Теоретический чертеж", "Габаритный чертеж",
        "Электромонтажный чертеж", "Монтажный чертеж", "Упаковочный чертеж",
        "Спецификация", "Ведомость спецификаций", "Ведомость ссылочных документов", "Ведомость покупных изделий",
        "Ведомость разрешения применения покупных изделий", "Ведомость держателей подлинников",
        "Ведомость технического предложения", "Ведомость эскизного проекта", "Ведомость технического проекта",
        "Ведомость эксплуатационных документов", "Ведомость ЗИП",
        "Пояснительная записка", "Технические условия", "Программа и методика испытаний", "Таблица", "Расчет",
        "Инструкция", "Руководство по эксплуатации", "Паспорт", "Формуляр", "Этикетка",
        "Перечень элементов", "Таблица соединений", "Таблица подключения",
        "Схема электрическая принципиальная", "Схема электрическая структурная", "Схема электрическая функциональная",
        "Схема электрическая соединений", "Схема электрическая подключения", "Схема электрическая общая",
        "Схема электрическая расположения", "Схема электрическая",
        "Схема гидравлическая принципиальная", "Схема пневматическая принципиальная", "Схема кинематическая принципиальная",
        "Схема структурная", "Схема функциональная", "Схема принципиальная", "Схема соединений", "Схема подключения",
        "Схема общая", "Схема расположения",
    }.OrderByDescending(t => t.Length).ToArray();

    /// <summary>Первые слова, с которых начинается тип документа: по ним в красной области
    /// последняя строка считается типом, даже если такого типа нет в справочнике.</summary>
    private static readonly string[] FirstWords =
    [
        "чертеж", "сборочный", "габаритный", "монтажный", "электромонтажный", "теоретический", "упаковочный",
        "спецификация", "ведомость", "пояснительная", "технические", "программа", "схема", "перечень", "таблица",
        "расчет", "инструкция", "руководство", "паспорт", "формуляр", "этикетка",
    ];

    /// <summary>Ключ сравнения: кириллица вместо двойников, «е» вместо «ё», нижний регистр,
    /// одиночные пробелы.</summary>
    public static string Key(string s) =>
        string.Join(' ', TextRules.FoldToCyrillic(s).Replace('ё', 'е').Replace('Ё', 'Е').ToLowerInvariant()
            .Split(' ', StringSplitOptions.RemoveEmptyEntries));

    /// <summary>Тип из справочника, если строка совпадает с ним; иначе null.</summary>
    public static string? Canonical(string text)
    {
        var key = Key(text);
        return Known.FirstOrDefault(t => Key(t) == key);
    }

    /// <summary>Строка начинается словом, с которого начинаются типы документов.</summary>
    public static bool StartsLikeType(string line)
    {
        var first = Key(line).Split(' ', 2)[0];
        return FirstWords.Contains(first);
    }

    /// <summary>Известный тип в конце строки: (часть до типа, тип из справочника) или null.</summary>
    public static (string Before, string Type)? SplitSuffix(string line)
    {
        var words = line.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        for (var take = Math.Min(words.Length - 1, 6); take >= 1; take--)
        {
            var tail = string.Join(' ', words[^take..]);
            if (Canonical(tail) is { } type)
                return (string.Join(' ', words[..^take]), type);
        }
        return null;
    }
}
